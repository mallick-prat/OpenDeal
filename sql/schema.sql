-- =============================================================================
-- Security lockdown (Supabase). See the header comment; do not skip.
-- =============================================================================
-- 1) Row Level Security on every table. With no policies this denies the
--    API roles everything and is a no-op for the owner role the app connects
--    as (owners bypass RLS unless FORCE is set; it deliberately is not).
do $$
declare r record;
begin
  for r in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', r.tablename);
  end loop;
end $$;

-- 2) Strip the API roles' privileges, and 3) stop future tables (created at
--    runtime by the app) from auto-granting to them. Only meaningful where
--    those roles exist (Supabase); skipped on plain Postgres.
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon')
     and exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on all tables    in schema public from anon, authenticated';
    execute 'revoke all on all sequences in schema public from anon, authenticated';
    execute 'revoke all on all functions in schema public from anon, authenticated';
    execute 'alter default privileges in schema public revoke all on tables    from anon, authenticated';
    execute 'alter default privileges in schema public revoke all on sequences from anon, authenticated';
    execute 'alter default privileges in schema public revoke all on functions from anon, authenticated';
  end if;
end $$;
