-- =============================================================================
-- OpenDeal: database schema (PostgreSQL 14+; tested on 16, also fine on Supabase/Neon)
-- =============================================================================
-- Idempotent: safe to run more than once. Applied by `npm run db:setup`.
--
-- What's here:
--   1. The tables the app reads and writes.
--   2. Generated columns on deals (name_base, search_tsv) that stay in sync by themselves.
--   3. A security lockdown (Row Level Security + revoked API grants). On
--      Supabase this is NOT optional: the project's public "anon" key is
--      shipped to browsers, and without this anyone holding it could read your
--      deals, mail, and OAuth tokens over the auto-generated REST API. The app
--      itself never uses that API; it talks to Postgres directly.
--
-- Naming notes (historical, not worth a risky rename):
--   deals.gid              the deal id (text; "local-<uuid>" for deals made here)
--   deals.schools          free-form tags (label is configurable, see
--                          src/config/crm.config.ts)
--   network_people         people (founders etc.); "network" is vestigial
--   deals.section_gid      the board column; equals the stage key
-- =============================================================================

